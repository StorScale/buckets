func pkgDir() string {
	info, _ := debug.ReadBuildInfo()
	for _, d := range info.Deps {
		if d.Path == "github.com/minio/pkg/v3" {
			return filepath.Join(os.Getenv("GOMODCACHE"), "github.com/minio/pkg/v3@"+d.Version)
		}
	}
	panic("minio/pkg not found")
}

// Every string constant in the policy package (and its condition package).
func stringConstants(dir string) []string {
	fset := token.NewFileSet()
	seen := map[string]bool{}
	for _, sub := range []string{"policy", "policy/condition"} {
		pkgs, err := parser.ParseDir(fset, filepath.Join(dir, sub), func(fi os.FileInfo) bool {
			return !strings.HasSuffix(fi.Name(), "_test.go")
		}, 0)
		if err != nil {
			panic(err)
		}
		for _, p := range pkgs {
			ast.Inspect(p, func(n ast.Node) bool {
				if bl, ok := n.(*ast.BasicLit); ok && bl.Kind == token.STRING {
					if s, err := strconv.Unquote(bl.Value); err == nil {
						seen[s] = true
					}
				}
				return true
			})
		}
	}
	out := []string{}
	for s := range seen {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func cstr(s string) string { return strconv.Quote(s) }

func validates(stmt map[string]any) bool {
	doc, _ := json.Marshal(map[string]any{"Version": "2012-10-17", "Statement": []any{stmt}})
	_, err := policy.ParseConfig(bytes.NewReader(doc))
	return err == nil
}

func tables() {
	consts := stringConstants(pkgDir())
	var s3, obj, admin, sts, kms []string
	for _, c := range consts {
		if strings.ContainsAny(c, "*?") && c != "s3:*" && c != "admin:*" && c != "sts:*" && c != "kms:*" {
			continue
		}
		a := policy.Action(c)
		switch {
		case strings.HasPrefix(c, "s3:") && a.IsValid() && !strings.ContainsAny(c[3:], "*?") || c == "s3:*":
			s3 = append(s3, c)
			if a.IsObjectAction() {
				obj = append(obj, c)
			}
		case strings.HasPrefix(c, "admin:") && policy.AdminAction(c).IsValid():
			admin = append(admin, c)
		case strings.HasPrefix(c, "sts:") && policy.STSAction(c).IsValid():
			sts = append(sts, c)
		case strings.HasPrefix(c, "kms:") && policy.KMSAction(c).IsValid():
			kms = append(kms, c)
		}
	}
	keys := []string{}
	for _, k := range condition.AllSupportedKeys {
		keys = append(keys, string(k))
	}
	common := map[string]bool{}
	for _, k := range condition.CommonKeys {
		common[string(k)] = true
	}
	keyIndex := map[string]int{}
	for i, k := range keys {
		keyIndex[k] = i
	}

	w := os.Stdout
	fmt.Fprintln(w, "/* Generated by tools/policygen from github.com/minio/pkg/v3 v3.1.3 policy. DO NOT EDIT. */")
	emit := func(name string, list []string) {
		fmt.Fprintf(w, "static const char *const %s[] = {\n", name)
		for _, s := range list {
			fmt.Fprintf(w, "    %s,\n", cstr(s))
		}
		fmt.Fprintf(w, "};\n#define %s_N %d\n", strings.ToUpper(name), len(list))
	}
	emit("k_s3_actions", s3)
	emit("k_object_actions", obj)
	emit("k_admin_actions", admin)
	emit("k_sts_actions", sts)
	emit("k_kms_actions", kms)
	emit("k_cond_keys", keys)
	fmt.Fprintf(w, "/* Bit i: k_cond_keys[i] is a common key (usable with any action, substituted in resources). */\n")
	fmt.Fprintf(w, "static const bool k_cond_common[] = {")
	for _, k := range keys {
		fmt.Fprintf(w, "%v,", common[k])
	}
	fmt.Fprintln(w, "};")

	// Condition keys each action accepts, probed through Validate.
	probe := func(action string, resource bool) []bool {
		allowed := make([]bool, len(keys))
		for i, k := range keys {
			st := map[string]any{"Effect": "Allow", "Action": action,
				"Condition": map[string]any{"Null": map[string]any{k: "true"}}}
			if resource {
				st["Resource"] = "arn:aws:s3:::*"
			}
			allowed[i] = validates(st)
		}
		return allowed
	}
	emitKeys := func(name string, actions []string, resource bool) {
		fmt.Fprintf(w, "static const bool %s[][%d] = {\n", name, len(keys))
		for _, a := range actions {
			fmt.Fprintf(w, "    {")
			for _, b := range probe(a, resource) {
				if b {
					fmt.Fprint(w, "1,")
				} else {
					fmt.Fprint(w, "0,")
				}
			}
			fmt.Fprintf(w, "}, /* %s */\n", a)
		}
		fmt.Fprintln(w, "};")
	}
	emitKeys("k_s3_action_keys", s3, true)
	emitKeys("k_admin_action_keys", admin, false)
	emitKeys("k_sts_action_keys", sts, false)
	_ = keyIndex
}

