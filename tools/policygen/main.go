// Command policygen emits C tables and golden vectors for Buckets' IAM
// policy engine from MinIO's own github.com/minio/pkg/v3/policy (v3.1.3,
// the version MinIO RELEASE.2025-10-15 links):
//
//	cd tools/policygen && go run . tables  > ../../src/iam/policy_tables.inc
//	cd tools/policygen && go run . vectors > ../../tests/unit/policy_vectors.inc
//
// Tables are derived from the package's behaviour, not transcribed: every
// string constant in its sources is classified with the package's own
// predicates, and per-action condition keys are probed through Validate.
// Vectors are random policies and requests evaluated by the real library.
