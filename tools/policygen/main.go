func randCondition() map[string]any {
	switch rng.Intn(9) {
	case 0:
		return map[string]any{"StringEquals": map[string]any{"s3:prefix": pick([]any{"", "2024/", []string{"a/", "b/"}})}}
	case 1:
		return map[string]any{"StringLike": map[string]any{"s3:prefix": pick([]any{"2024/*", "*", []string{"a*", "b?"}})}}
	case 2:
		return map[string]any{"IpAddress": map[string]any{"aws:SourceIp": pick([]any{"10.0.0.0/8", "192.168.1.5", []string{"10.1.0.0/16", "172.16.0.0/12"}})}}
	case 3:
		return map[string]any{"NotIpAddress": map[string]any{"aws:SourceIp": "10.0.0.0/8"}}
	case 4:
		return map[string]any{"Bool": map[string]any{"aws:SecureTransport": pick([]any{"true", "false", true})}}
	case 5:
		return map[string]any{"Null": map[string]any{"s3:prefix": pick([]any{"true", "false"})}}
	case 6:
		return map[string]any{"StringNotEquals": map[string]any{"aws:username": pick([]any{"alice", []string{"bob", "carol"}})}}
	case 7:
		return map[string]any{"NumericLessThanEquals": map[string]any{"s3:max-keys": pick([]any{"10", 100})}}
	default:
		return map[string]any{pick([]string{"ForAnyValue:StringEquals", "ForAllValues:StringEquals", "StringEqualsIgnoreCase"}):
			map[string]any{"aws:username": pick([]any{"Alice", []string{"alice", "bob"}})}}
	}
}

func randStatement() map[string]any {
	st := map[string]any{"Effect": pick([]string{"Allow", "Allow", "Deny"})}
	acts := []string{}
	for n := 1 + rng.Intn(3); len(acts) < n; {
		a := pick(actionPool)
		if !contains(acts, a) {
			acts = append(acts, a)
		}
	}
	if rng.Intn(8) == 0 {
		st["NotAction"] = acts
	} else if len(acts) == 1 && rng.Intn(2) == 0 {
		st["Action"] = acts[0]
	} else {
		st["Action"] = acts
	}
	res := []string{}
	for n := 1 + rng.Intn(2); len(res) < n; {
		r := pick(resourcePool)
		if !contains(res, r) {
			res = append(res, r)
		}
	}
	if rng.Intn(8) == 0 {
		st["NotResource"] = res
	} else {
		st["Resource"] = res
	}
	if rng.Intn(3) == 0 {
		st["Condition"] = randCondition()
	}
	return st
}

func contains(xs []string, x string) bool {
	for _, y := range xs {
		if x == y {
			return true
		}
	}
	return false
}

type args struct {
	Action, Bucket, Object string
	Owner                  bool
	Cond                   map[string][]string
}

func randArgs() args {
	a := args{Action: pick([]string{"s3:GetObject", "s3:PutObject", "s3:ListBucket", "s3:DeleteObject",
		"s3:GetObjectVersion", "s3:ListAllMyBuckets", "s3:GetBucketLocation", "s3:CreateBucket", "s3:PutObjectTagging"}),
		Bucket: pick([]string{"photos", "docs", "home", "alice", "other", ""}),
		Object: pick([]string{"", "", "2024/a.jpg", "public/x", "alice/notes", "a.txt", "ab.txt", "bob/x", "2024/", "/lead", "x/../y"}),
		Owner:  rng.Intn(10) == 0, Cond: map[string][]string{}}
	if rng.Intn(2) == 0 {
		a.Cond["prefix"] = []string{pick([]string{"", "2024/", "a/", "bb", "2024/x"})}
	}
	if rng.Intn(2) == 0 {
		a.Cond["SourceIp"] = []string{pick([]string{"10.1.2.3", "192.168.1.5", "172.20.0.1", "8.8.8.8", "::1", "junk"})}
	}
	if rng.Intn(2) == 0 {
		a.Cond["SecureTransport"] = []string{pick([]string{"true", "false"})}
	}
	if rng.Intn(2) == 0 {
		a.Cond["username"] = []string{pick([]string{"alice", "bob", "Alice", ""})}
	}
	if rng.Intn(3) == 0 {
		a.Cond["max-keys"] = []string{pick([]string{"5", "10", "1000", "x"})}
	}
	if rng.Intn(4) == 0 && len(a.Cond["username"]) > 0 {
		a.Cond["username"] = append(a.Cond["username"], "carol")
	}
	return a
}

func condC(m map[string][]string) string {
	keys := []string{}
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	for _, k := range keys {
		b.WriteString(k)
		b.WriteString("=")
		b.WriteString(strings.Join(m[k], ","))
		b.WriteString(";")
	}
	return b.String()
}

